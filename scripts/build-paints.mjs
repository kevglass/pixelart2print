import { writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/Arcturus5404/miniature-paints/main/paints/Army_Painter.md';

// Speedpaints/washes/primers are deliberately excluded: they're translucent and
// give the wrong look for flat, opaque pixel colours.
const RANGES = { 'Warpaints Fanatic': 'fanatic', 'Warpaints': 'warpaints' };
const NOT_PAINTS = new Set(['Gloss Varnish', 'Warpaints Mixing Medium']);
const METALLICS = new Set([
  'Bright Gold', 'Cobalt Metal', 'Death Metal', 'Evil Chrome', 'Glittering Green', 'Greedy Gold',
  'Gun Metal', 'Mithril', 'Plate Mail Metal', 'Red Copper', 'Rough Iron', 'Runic Cobalt',
  'Shining Silver', 'Tainted Gold', 'True Brass', 'True Copper', 'Weapon Bronze',
]);

const md = await (await fetch(SOURCE)).text();
const paints = [];
for (const line of md.split('\n')) {
  const cols = line.split('|').map((c) => c.trim());
  if (cols.length < 8) continue;
  const [, name, code, set, r, g, b] = cols;
  const range = RANGES[set];
  if (!range || NOT_PAINTS.has(name)) continue;
  const hex = '#' + [r, g, b].map((v) => Number(v).toString(16).padStart(2, '0')).join('').toUpperCase();
  paints.push({ name: name.replace('’', "'"), code: code === 'null' ? undefined : code, range, hex, metallic: METALLICS.has(name) });
}
paints.sort((a, b) => a.range.localeCompare(b.range) || a.name.localeCompare(b.name));

const rows = paints.map((p) =>
  `  { name: ${JSON.stringify(p.name)}, ${p.code ? `code: ${JSON.stringify(p.code)}, ` : ''}range: '${p.range}', hex: '${p.hex}'${p.metallic ? ', metallic: true' : ''} },`);

writeFileSync('src/paints/armyPainter.ts', `// GENERATED by scripts/build-paints.mjs - do not edit by hand.
// Colour data from https://github.com/Arcturus5404/miniature-paints
// MIT License, Copyright (c) 2022 Rick Fleuren.
// Hex values are approximations of the bottled colour; always check against the real pot.

export type PaintRange = 'fanatic' | 'warpaints';

export interface Paint {
  name: string;
  code?: string;
  range: PaintRange;
  hex: string;
  metallic?: boolean;
}

export const RANGE_LABELS: Record<PaintRange, string> = {
  fanatic: 'Warpaints Fanatic',
  warpaints: 'Warpaints (classic)',
};

export const ARMY_PAINTER_PAINTS: Paint[] = [
${rows.join('\n')}
];
`);
console.log(`Wrote ${paints.length} paints`);
